EQUIPMENT: dict[str, tuple[str, str, list[str]]] = {
    "Main Engine": ("HD", "Halvorsen Diesel", ["Piston ring set", "Cylinder liner", "Exhaust valve", "Connecting rod bearing", "Fuel pump plunger"]),
    "Auxiliary Engine": ("TE", "Tenmark Engines", ["Fuel injector nozzle", "Cylinder head gasket set", "Lube oil filter element", "Water pump seal kit", "Crankshaft bearing shell"]),
    "Purifier": ("PP", "Pelagic Purifiers", ["Disc stack", "Bowl seal ring", "Feed pump impeller", "Bearing set", "Gravity disc"]),
    "Boiler": ("BB", "Brennfeld Boilers", ["Burner nozzle", "Flame scanner", "Gauge glass set", "Safety valve spring", "Furnace refractory kit"]),
    "Air Compressor": ("AC", "Arkwright Compressors", ["Valve plate assembly", "Piston ring kit", "Unloader valve", "Intercooler gasket", "Drive belt set"]),
    "Ballast Pump": ("CP", "Coralis Pumps", ["Impeller kit", "Mechanical seal", "Wear ring set", "Shaft sleeve", "Bearing housing"]),
    "Cargo Pump": ("VC", "Vantor Cargo Pumps", ["Impeller", "Casing wear plate", "Gland packing set", "Coupling insert", "Suction strainer"]),
    "Steering Gear": ("SS", "Stenhamn Steering", ["Hydraulic ram seal kit", "Rudder carrier bearing", "Servo valve", "Pump shaft seal", "Pressure relief valve"]),
    "Fuel Injection System": ("LF", "Lindqvist Fuel Systems", ["Injector assembly", "High pressure pipe", "Plunger and barrel set", "Delivery valve", "Fuel rail pressure sensor"]),
    "Turbocharger": ("MT", "Marlow Turbo", ["Cartridge assembly", "Compressor wheel", "Nozzle ring", "Bearing kit", "Gasket and seal set"]),
}
VARIANTS = ["standard", "heavy duty"]
PORTS = ["Singapore", "Rotterdam", "Fujairah", "Houston", "Dubai", "Busan"]
SUPPLIERS = ["S01", "S02", "S03"]
PLANTED_PARTS = {  # (equipment, part, variant) -> (part_no, base price)
    ("Main Engine", "Piston ring set", "standard"): ("HD-1123", 420.00),
    ("Auxiliary Engine", "Fuel injector nozzle", "standard"): ("TE-2207", 185.50),
    ("Ballast Pump", "Impeller kit", "standard"): ("CP-3310", 960.00),
    ("Purifier", "Disc stack", "standard"): ("PP-4102", 2750.00),
}
PLANTED_ROWS = {  # (part_no, supplier) -> (price, moq, lead_time_days, stock_port)
    ("HD-1123", "S01"): (420.00, 4, 21, "Singapore"),
    ("HD-1123", "S02"): (433.00, 2, 28, "Rotterdam"),
    ("HD-1123", "S03"): (408.50, 6, 18, "Singapore"),
    ("TE-2207", "S02"): (185.50, 2, 14, "Rotterdam"),
    ("CP-3310", "S03"): (960.00, 1, 35, "Fujairah"),
    ("PP-4102", "S01"): (2750.00, 1, 45, "Houston"),
}


def make_catalogue(path: Path, seed: int = 11) -> list[dict[str, Any]]:
    rng = random.Random(seed)
    rows: list[dict[str, Any]] = []
    used_numbers: set[str] = {v[0] for v in PLANTED_PARTS.values()}
    for equipment, (prefix, maker, parts) in EQUIPMENT.items():
        for part in parts:
            for variant in VARIANTS:
                planted = PLANTED_PARTS.get((equipment, part, variant))
                if planted:
                    part_no, base = planted
                else:
                    while (part_no := f"{prefix}-{rng.randint(1000, 9899)}") in used_numbers:
                        pass
                    used_numbers.add(part_no)
                    base = round(rng.choice([35, 60, 90, 140, 220, 350, 520, 780, 1200, 1900]) * rng.uniform(0.8, 1.3), 2)
                    if variant == "heavy duty":
                        base = round(base * 1.35, 2)
                for supplier in SUPPLIERS:
                    if (part_no, supplier) in PLANTED_ROWS:
                        price, moq, lead, port = PLANTED_ROWS[(part_no, supplier)]
                    else:
                        price = round(base * rng.uniform(0.94, 1.08), 2)
                        moq = rng.choice([1, 1, 2, 2, 4, 5, 10])
                        lead = rng.choice([7, 10, 14, 18, 21, 28, 35, 42, 56])
                        port = rng.choice(PORTS)
                    rows.append({
                        "part_no": part_no, "description": f"{part} ({variant})", "equipment": equipment,
                        "maker": maker, "supplier_id": supplier, "unit_price_usd": f"{price:.2f}",
                        "moq": moq, "lead_time_days": lead, "stock_port": port,
                    })
    rows.sort(key=lambda r: (r["part_no"], r["supplier_id"]))
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    return rows


# ---------------------------------------------------------------- orchestration ------------

def synthesize(demo: str, clauses_per_section: int) -> None:
    plan = yaml.safe_load((SYNTH / demo / "plan.yaml").read_text(encoding="utf-8"))
    cfg = load_config(ROOT / "forgeai.yaml")
    cfg = cfg.model_copy(update={"cache_dir": ROOT / ".cache"})
    set_client(LLMClient(cfg, trace_path=SYNTH / demo / "synthesis_trace.jsonl"))
    out_docs = ROOT / "data" / demo / "docs"
    out_docs.mkdir(parents=True, exist_ok=True)
    (ROOT / "data" / demo / "brief.txt").write_text(plan["brief"].strip() + "\n", encoding="utf-8")

    facts_out: list[dict[str, Any]] = []
    for doc in plan["documents"]:
        print(f"== {doc['file']}", flush=True)
        generated: list[tuple[str, list[str]]] = []
        for section in doc["sections"]:
            print(f"  - {section['title']}", flush=True)
            generated.append((section["title"], generate_section(plan, doc, section, clauses_per_section, cfg)))
        (SYNTH / demo / "generated").mkdir(exist_ok=True)
        (SYNTH / demo / "generated" / f"{Path(doc['file']).stem}.json").write_text(
            json.dumps({"title": doc["title"], "sections": generated}, indent=2), encoding="utf-8")
        render_pdf(out_docs / doc["file"], plan, doc, generated)
        loaded = load_document(out_docs / doc["file"])
        text = normalize(loaded.canonical_text).lower()
        print(f"  pages: {loaded.page_count}", flush=True)
        for section in doc["sections"]:
            for fact in section.get("facts") or []:
                found = all(normalize(m).lower() in text for m in fact["must_contain"])
                facts_out.append({"id": fact["id"], "kind": "planted_fact", "doc": doc["file"],
                                  "section": section["title"], "statement": fact["statement"],
                                  "must_contain": fact["must_contain"], "verified_in_pdf": found})
                if not found:
                    raise RuntimeError(f"planted fact {fact['id']} missing from rendered {doc['file']}")
        if doc.get("ambiguity"):
            facts_out.append({"id": doc["ambiguity"]["id"], "kind": "ambiguity", "doc": doc["file"],
                              "statement": doc["ambiguity"]["statement"], "refs": doc["ambiguity"]["refs"]})
    if demo == "spares_procurement":
        rows = make_catalogue(out_docs / "spares_catalogue.csv")
        print(f"catalogue rows: {len(rows)}", flush=True)
        for (part_no, supplier), (price, moq, lead, port) in PLANTED_ROWS.items():
            facts_out.append({"id": f"CSV-{part_no}-{supplier}", "kind": "csv_row", "doc": "spares_catalogue.csv",
                              "statement": f"{part_no} from {supplier}: unit_price_usd {price:.2f}, moq {moq}, lead_time_days {lead}, stock_port {port}",
                              "must_contain": [part_no, f"{price:.2f}"]})
        facts_out.append({"id": "DERIVED-1", "kind": "derived", "doc": "spares_catalogue.csv + terms_norvik_marine_supply.pdf",
                          "statement": "12 x HD-1123 from S01 = USD 5,040.00, which falls in the S01 5% tier, so USD 4,788.00 after discount",
                          "must_contain": []})
        facts_out.append({"id": "DERIVED-2", "kind": "derived", "doc": "spares_catalogue.csv + terms_norvik_marine_supply.pdf",
                          "statement": "6 x PP-4102 from S01 = USD 16,500.00, which falls in the S01 8% tier, so USD 15,180.00 after discount",
                          "must_contain": []})
    for gap in plan.get("planted_gaps", []):
        facts_out.append({"id": gap["id"], "kind": "planted_gap", "statement": gap["description"]})
    sheet = {"demo": demo, "company": plan["company"], "expected_tools": plan.get("expected_tools", []),
             "not_expected_tools": plan.get("not_expected_tools", []), "facts": facts_out}
    (SYNTH / demo / "fact_sheet.json").write_text(json.dumps(sheet, indent=2), encoding="utf-8")
    print(f"fact sheet: {len(facts_out)} entries", flush=True)


if __name__ == "__main__":
    name = sys.argv[1]
    synthesize(name, int(sys.argv[2]) if len(sys.argv) > 2 else (6 if name == "hr_shore" else 7))
