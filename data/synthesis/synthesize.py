"""Synthesize a demo corpus from a plan: LLM-written clauses, rendered to real PDFs.

Usage (from the repo root):  python data/synthesis/synthesize.py hr_shore
                             python data/synthesis/synthesize.py spares_procurement

The plan lists PLANTED facts. Each section is generated by the local LLM through
``call_structured`` (prompt: data/synthesis/prompts/section.md). Generation is accepted
only if (a) every planted ``must_contain`` string appears, (b) no number outside the
planted facts appears, and (c) no forbidden word appears; otherwise it retries with a new
seed. After rendering, every planted fact is re-verified in the text extracted from the PDF.
The hidden ``fact_sheet.json`` is written next to the plan. forgeai/evals/ never reads it.
"""

from __future__ import annotations

import csv
import json
import random
import re
import sys
from pathlib import Path
from typing import Any

import yaml
from pydantic import BaseModel
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import PageBreak, Paragraph, SimpleDocTemplate, Spacer

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from forgeai.config import load_config  # noqa: E402
from forgeai.ingest.loaders import load_document  # noqa: E402
from forgeai.llm import LLMClient, call_structured, set_client  # noqa: E402
from forgeai.textmatch import normalize  # noqa: E402

SYNTH = Path(__file__).resolve().parent
MAX_ATTEMPTS = 6
MIN_CLAUSES = 4
NUMBER = re.compile(r"\d[\d,]*(?:\.\d+)?")


class Clauses(BaseModel):
    clauses: list[str]


def numbers_in(text: str) -> set[str]:
    """Numeric tokens, ignoring identifiers such as supplier ids (S01) that merely contain digits."""
    without_ids = re.sub(r"\b[A-Za-z]+-?\d+\b", " ", text)
    return {n.replace(",", "").rstrip(".") for n in NUMBER.findall(without_ids)}


WORD_NUMBER = re.compile(
    r"""(?:one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve|fourteen|fifteen|twenty|thirty|forty|fifty|sixty|ninety|hundred)"""
    r"""\s+(?:(?:working|business|calendar|consecutive)\s+)?(?:days?|weeks?|months?|years?|hours?|percent)""",
    re.IGNORECASE,
)


def clause_problems(clause: str, allowed: set[str], forbidden: list[str], planted: str = "") -> list[str]:
    """Problems with ONE clause. Bad clauses are dropped; the section is judged on what remains."""
    problems: list[str] = []
    stray = numbers_in(clause) - allowed
    if stray:
        problems.append(f"numbers not in the plan: {sorted(stray)}")
    lowered = clause.lower()
    for match in WORD_NUMBER.finditer(clause):  # spelled-out quantities that are not planted
        if match.group(0).lower() not in planted:
            problems.append(f"spelled-out quantity not in the plan: {match.group(0)!r}")
    problems += [f"forbidden word {w!r}" for w in forbidden if re.search(rf"\b{re.escape(w.lower())}\b", lowered)]
    if re.match(r"^\s*(\d+[.)]|[-*•])\s", clause):
        problems.append("starts with a list marker")
    return problems


def check_section(clauses: list[str], facts: list[dict[str, Any]], n: int) -> list[str]:
    """Problems with the kept clauses as a whole (empty list = accepted)."""
    text = " ".join(clauses)
    problems: list[str] = []
    if not MIN_CLAUSES <= len(clauses) <= n + 2:
        problems.append(f"expected {MIN_CLAUSES} to {n} usable clauses, got {len(clauses)}")
    for fact in facts:
        for needle in fact["must_contain"]:
            if normalize(needle).lower() not in normalize(text).lower():
                problems.append(f"missing planted text {needle!r} ({fact['id']})")
    return problems


def generate_section(plan: dict[str, Any], doc: dict[str, Any], section: dict[str, Any], n: int, cfg) -> list[str]:
    facts = section.get("facts") or []
    fact_lines = "\n".join(f'- {f["statement"]}. Exact text to include: ' + "; ".join(f'"{m}"' for m in f["must_contain"])
                           for f in facts) or "(none: write general clauses without any numbers)"
    last: list[str] = []
    for attempt in range(MAX_ATTEMPTS):
        result = call_structured(
            role="synthesis.section",
            prompt_id="section",
            variables={
                "company": plan["company"], "document": doc["title"], "section": section["title"],
                "brief": section["brief"], "facts": fact_lines, "n_clauses": n, "min_clauses": MIN_CLAUSES,
                "forbidden": ", ".join(plan.get("forbidden") or []) or "(none)",
            },
            schema=Clauses,
            model=cfg.agent_model.name,
            temperature=0.4,
            seed=cfg.agent_model.seed + attempt,
            fallback=Clauses(clauses=[]),
            prompts_dir=SYNTH / "prompts",
        )
        clauses = [re.sub(r"\s+", " ", c).strip() for c in result.clauses if c.strip()]
        sentences = [x for c in clauses for x in re.split(r"(?<=[.!?])\s+", c) if x]
        per = max(1, round(len(sentences) / n))  # regroup into about n short numbered clauses
        clauses = [" ".join(sentences[i:i + per]) for i in range(0, len(sentences), per)]
        allowed = set().union(*[numbers_in(" ".join(f["must_contain"])) for f in facts]) if facts else set()
        planted_text = " ".join(m for f in facts for m in f["must_contain"]).lower()
        kept = []
        for clause in clauses:
            bad = clause_problems(clause, allowed, plan.get("forbidden") or [], planted_text)
            if bad:
                print(f"    dropped clause ({bad[0]})", flush=True)
            else:
                kept.append(clause)
        clauses = kept
        last = check_section(clauses, facts, n)
        if not last:
            return clauses
        print(f"    retry {attempt + 1}: {last}", flush=True)
    raise RuntimeError(f"section {section['title']!r} failed after {MAX_ATTEMPTS} attempts: {last}")


def render_pdf(path: Path, plan: dict[str, Any], doc: dict[str, Any], sections: list[tuple[str, list[str]]]) -> None:
    title = ParagraphStyle("t", fontName="Helvetica-Bold", fontSize=20, leading=26, spaceAfter=6)
    meta = ParagraphStyle("m", fontName="Helvetica", fontSize=10.5, leading=14, spaceAfter=14, textColor="#444444")
    head = ParagraphStyle("h", fontName="Helvetica-Bold", fontSize=14, leading=18, spaceBefore=14, spaceAfter=6)
    body = ParagraphStyle("b", fontName="Helvetica", fontSize=10.5, leading=15, spaceAfter=7)
    story: list[Any] = [
        Paragraph(doc["title"], title),
        Paragraph(f"{plan['company'].split(' (')[0]} &nbsp;|&nbsp; Effective date: {doc['effective']}", meta),
    ]
    for number, (heading, clauses) in enumerate(sections, start=1):
        story.append(Paragraph(f"{number}. {heading}", head))
        for index, clause in enumerate(clauses, start=1):
            safe = clause.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            story.append(Paragraph(f"{number}.{index} {safe}", body))
    page_note = f"{plan['company'].split(' (')[0]}: {doc['title']}"

    def footer(canvas, document) -> None:  # noqa: ANN001
        canvas.setFont("Helvetica", 8.5)
        canvas.drawString(20 * mm, 12 * mm, page_note)
        canvas.drawRightString(A4[0] - 20 * mm, 12 * mm, f"Page {document.page}")

    SimpleDocTemplate(str(path), pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm,
                      topMargin=20 * mm, bottomMargin=20 * mm, title=doc["title"]).build(
        story, onFirstPage=footer, onLaterPages=footer)


